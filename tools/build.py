"""
Validate every detection and build the outputs that are generated from them.

  python tools/build.py            # validate + write docs/INDEX.md and deploy/analytics-rules.json
  python tools/build.py --check    # validate only (used by CI); fails if generated files are stale

Each detection is a YAML file under detections/<category>/. The schema is
enforced here so a broken rule never reaches Sentinel.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import uuid
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DETECTIONS = ROOT / "detections"
INDEX = ROOT / "docs" / "INDEX.md"
ARM = ROOT / "deploy" / "analytics-rules.json"
LAYER = ROOT / "deploy" / "attack-navigator-layer.json"

REQUIRED = ["id", "name", "description", "severity", "status", "tactics", "techniques",
            "data_sources", "query_frequency", "query_period", "trigger_threshold", "query",
            "entity_mappings", "tuning", "false_positives", "test"]
SEVERITIES = {"Informational", "Low", "Medium", "High"}
STATUSES = {"lab-test-pending", "lab-tested", "production"}
# Sentinel's tactic names (no spaces), from the MITRE ATT&CK Enterprise matrix
TACTICS = {"Reconnaissance", "ResourceDevelopment", "InitialAccess", "Execution", "Persistence",
           "PrivilegeEscalation", "DefenseEvasion", "CredentialAccess", "Discovery",
           "LateralMovement", "Collection", "CommandAndControl", "Exfiltration", "Impact"}
ENTITY_TYPES = {"Account", "Host", "IP", "URL", "File", "Process", "AzureResource", "MailMessage",
                "CloudApplication", "DNS", "FileHash", "RegistryKey", "Mailbox"}
TECHNIQUE_RE = re.compile(r"^T\d{4}(\.\d{3})?$")
DURATION_RE = re.compile(r"^P(T\d+[HM]|\d+D)$")


def load_all() -> list[tuple[Path, dict]]:
    out = []
    for p in sorted(DETECTIONS.rglob("*.yaml")):
        with p.open() as f:
            out.append((p, yaml.safe_load(f)))
    return out


def iso_to_minutes(d: str) -> int:
    m = re.match(r"^PT(\d+)([HM])$", d)
    if m:
        return int(m[1]) * (60 if m[2] == "H" else 1)
    m = re.match(r"^P(\d+)D$", d)
    return int(m[1]) * 1440


def validate(path: Path, d: dict) -> list[str]:
    errs = []
    rel = path.relative_to(ROOT)
    if not isinstance(d, dict):
        return [f"{rel}: not a mapping"]
    for k in REQUIRED:
        if k not in d or d[k] in (None, "", []):
            errs.append(f"{rel}: missing '{k}'")
    if errs:
        return errs
    try:
        uuid.UUID(str(d["id"]))
    except ValueError:
        errs.append(f"{rel}: id is not a UUID")
    if d["severity"] not in SEVERITIES:
        errs.append(f"{rel}: severity must be one of {sorted(SEVERITIES)}")
    if d["status"] not in STATUSES:
        errs.append(f"{rel}: status must be one of {sorted(STATUSES)}")
    for t in d["tactics"]:
        if t not in TACTICS:
            errs.append(f"{rel}: unknown tactic '{t}'")
    for t in d["techniques"]:
        if not TECHNIQUE_RE.match(str(t)):
            errs.append(f"{rel}: technique '{t}' is not in T#### or T####.### form")
    for k in ("query_frequency", "query_period"):
        if not DURATION_RE.match(str(d[k])):
            errs.append(f"{rel}: {k} must be an ISO-8601 duration like PT1H or P1D")
    if not errs and iso_to_minutes(d["query_period"]) < iso_to_minutes(d["query_frequency"]):
        errs.append(f"{rel}: query_period shorter than query_frequency leaves gaps")
    q = d["query"]
    if q.count("(") != q.count(")"):
        errs.append(f"{rel}: unbalanced parentheses in query")
    for src in d["data_sources"]:
        if src not in q:
            errs.append(f"{rel}: data source '{src}' listed but not used in query")
    for em in d["entity_mappings"]:
        if em.get("entityType") not in ENTITY_TYPES:
            errs.append(f"{rel}: unknown entityType '{em.get('entityType')}'")
        for fm in em.get("fieldMappings", []):
            col = fm.get("columnName", "")
            if not re.search(rf"\b{re.escape(col)}\b", q):
                errs.append(f"{rel}: entity column '{col}' does not appear in the query output")
    if len(d["name"]) > 100:
        errs.append(f"{rel}: name longer than 100 chars")
    return errs


def build_index(items) -> str:
    lines = ["# Detection index", "",
             "Generated by `tools/build.py` — do not edit by hand.", "",
             "| Detection | Severity | ATT&CK | Data sources | Status |",
             "|---|---|---|---|---|"]
    for p, d in items:
        rel = p.relative_to(ROOT).as_posix()
        techs = ", ".join(f"[{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/)" for t in d["techniques"])
        lines.append(f"| [{d['name']}](../{rel}) | {d['severity']} | {techs} | {', '.join(d['data_sources'])} | {d['status']} |")
    tactic_counts: dict[str, int] = {}
    for _, d in items:
        for t in d["tactics"]:
            tactic_counts[t] = tactic_counts.get(t, 0) + 1
    lines += ["", "## Coverage by tactic", "", "| Tactic | Detections |", "|---|---|"]
    for t in sorted(TACTICS):
        lines.append(f"| {t} | {tactic_counts.get(t, 0)} |")
    return "\n".join(lines) + "\n"


def build_layer(items) -> dict:
    """MITRE ATT&CK Navigator layer: open it at https://mitre-attack.github.io/attack-navigator/ to see coverage."""
    by_tech: dict[str, list[str]] = {}
    for _, d in items:
        for t in d["techniques"]:
            by_tech.setdefault(t, []).append(d["name"])
    return {
        "name": "KQL Detection Library coverage",
        "versions": {"layer": "4.5", "navigator": "5.1.0", "attack": "16"},
        "domain": "enterprise-attack",
        "description": "Techniques covered by detections in github.com/sbsmith340/kql-detection-library. "
                       "Score = number of detections.",
        "techniques": [{"techniqueID": t, "score": len(names), "comment": "; ".join(sorted(names)),
                        "enabled": True, "showSubtechniques": True}
                       for t, names in sorted(by_tech.items())],
        "gradient": {"colors": ["#c6dbef", "#08519c"], "minValue": 0, "maxValue": 2},
        "legendItems": [{"label": "Covered by at least one detection", "color": "#6baed6"}],
        "showTacticRowBackground": True,
    }


def build_arm(items) -> dict:
    resources = []
    for _, d in items:
        resources.append({
            "type": "Microsoft.OperationalInsights/workspaces/providers/alertRules",
            "apiVersion": "2023-02-01",
            "name": f"[concat(parameters('workspace'), '/Microsoft.SecurityInsights/', '{d['id']}')]",
            "kind": "Scheduled",
            "properties": {
                "displayName": d["name"],
                "description": " ".join(d["description"].split()),
                "severity": d["severity"],
                "enabled": "[parameters('enableRules')]",
                "query": d["query"],
                "queryFrequency": d["query_frequency"],
                "queryPeriod": d["query_period"],
                "triggerOperator": "GreaterThan",
                "triggerThreshold": d["trigger_threshold"],
                "suppressionEnabled": False,
                "suppressionDuration": "PT5H",
                "tactics": d["tactics"],
                "techniques": sorted({t.split(".")[0] for t in d["techniques"]}),
                "entityMappings": d["entity_mappings"],
                "incidentConfiguration": {
                    "createIncident": True,
                    "groupingConfiguration": {
                        "enabled": True, "reopenClosedIncident": False, "lookbackDuration": "PT5H",
                        "matchingMethod": "AllEntities", "groupByEntities": [], "groupByAlertDetails": [],
                        "groupByCustomDetails": []}},
            },
        })
    return {
        "$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#",
        "contentVersion": "1.0.0.0",
        "parameters": {
            "workspace": {"type": "string", "metadata": {"description": "Log Analytics workspace name with Microsoft Sentinel enabled"}},
            "enableRules": {"type": "bool", "defaultValue": False,
                            "metadata": {"description": "Rules deploy disabled by default so they can be reviewed first"}},
        },
        "resources": resources,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    items = load_all()
    errors = [e for p, d in items for e in validate(p, d)]
    ids = [str(d["id"]) for _, d in items if isinstance(d, dict) and "id" in d]
    dupes = {i for i in ids if ids.count(i) > 1}
    errors += [f"duplicate id {i}" for i in sorted(dupes)]
    if errors:
        print("\n".join(errors))
        print(f"\n{len(errors)} problem(s) in {len(items)} detection(s)")
        return 1

    index = build_index(items)
    arm = json.dumps(build_arm(items), indent=2) + "\n"
    layer = json.dumps(build_layer(items), indent=2) + "\n"
    if args.check:
        stale = [p for p, c in ((INDEX, index), (ARM, arm), (LAYER, layer)) if not p.exists() or p.read_text() != c]
        if stale:
            print("Generated files are out of date; run python tools/build.py:",
                  ", ".join(str(p.relative_to(ROOT)) for p in stale))
            return 1
    else:
        INDEX.parent.mkdir(exist_ok=True)
        ARM.parent.mkdir(exist_ok=True)
        INDEX.write_text(index)
        ARM.write_text(arm)
        LAYER.write_text(layer)
    print(f"OK: {len(items)} detections valid")
    return 0


if __name__ == "__main__":
    sys.exit(main())
